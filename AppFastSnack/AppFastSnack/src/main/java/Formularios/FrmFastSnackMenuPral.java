    private void txtBancoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtBancoActionPerformed
        String metodo = cmbMetodopago.getSelectedItem().toString();

        if (metodo.equals("Transferencia Bancaria")
                || metodo.equals("Tarjeta de Débito")
                || metodo.equals("Tarjeta de Crédito")) {

            txtBanco.setEnabled(true);

        } else {
            txtBanco.setText("No aplica");
            txtBanco.setEnabled(false);
        }
    }//GEN-LAST:event_txtBancoActionPerformed

    private void chkConsumidorFinalItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_chkConsumidorFinalItemStateChanged
        if (evt.getStateChange() == java.awt.event.ItemEvent.SELECTED) {
            txtNombre.setText("Consumidor Final");
            txtCedula.setText("9999999999");
            txtNombre.setEditable(false);
            txtCedula.setEditable(false);
            txtTelefono.setText("----");
            txtBanco.setText("Efectivo");

            txtDireccion.requestFocus();

        } else {
            txtNombre.setText("");
            txtCedula.setText("");
            txtNombre.setEditable(true);
            txtCedula.setEditable(true);
        }
    }//GEN-LAST:event_chkConsumidorFinalItemStateChanged

