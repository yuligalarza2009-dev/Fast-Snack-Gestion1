    private boolean esConsumidorFinal = false;
    private void btnGuardarPedidoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarPedidoActionPerformed
        if (!esConsumidorFinal) {
            if (txtNombre.getText().trim().isEmpty()
                    || txtTelefono.getText().trim().isEmpty()
                    || txtCedula.getText().trim().isEmpty()
                    || txtDireccion.getText().trim().isEmpty()) {

                JOptionPane.showMessageDialog(
                        this,
                        "Debe completar todos los datos del cliente"
                );
                return;
            }
        }

        FrmPedidoExitoso exito = new FrmPedidoExitoso();

        exito.setVisible(true);

        this.dispose();
    }//GEN-LAST:event_btnGuardarPedidoActionPerformed

    private void btnBorrarPedidoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBorrarPedidoActionPerformed

        int respuesta = JOptionPane.showConfirmDialog(
                null,
                "¿Desea borrar todos los datos?",
                "Confirmar",
                JOptionPane.YES_NO_OPTION);
        if (respuesta == JOptionPane.YES_OPTION) {
            BorrarCampos();
        }
    }//GEN-LAST:event_btnBorrarPedidoActionPerformed

